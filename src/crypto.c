/* AES-128 and the legacy device's 1024-bit RSA handshake. No external crypto runtime.
 * This module is protocol-specific, not a general purpose cryptographic library. */
#include "crypto.h"
#include <string.h>

void secure_clear(void *p, size_t n) {
    volatile uint8_t *v = p;
    while (n--)
        *v++ = 0;
}
static uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    for (unsigned i = 0; i < 8; i++) {
        if (b & 1)
            r ^= a;
        a = (uint8_t)((a << 1) ^ ((a & 128) ? 0x1b : 0));
        b >>= 1;
    }
    return r;
}
