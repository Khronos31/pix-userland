void aes_init(aes128 *a, const uint8_t key[16]) {
    memcpy(a->round, key, 16);
    uint8_t rc = 1, t[4];
    for (unsigned i = 16; i < 176; i += 4) {
        memcpy(t, a->round + i - 4, 4);
        if (i % 16 == 0) {
            uint8_t x = t[0];
            t[0] = sbox[t[1]] ^ rc;
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[x];
            rc = mul(rc, 2);
        }
        for (unsigned j = 0; j < 4; j++)
            a->round[i + j] = a->round[i + j - 16] ^ t[j];
    }
}
static void add(uint8_t s[16], const uint8_t *key) {
    for (unsigned i = 0; i < 16; i++)
        s[i] ^= key[i];
}
static void shift(uint8_t s[16], int inv) {
    uint8_t t[16];
    for (unsigned r = 0; r < 4; r++)
        for (unsigned c = 0; c < 4; c++)
            t[r + 4 * c] = s[r + 4 * ((c + (inv ? 4 - r : r)) % 4)];
    memcpy(s, t, 16);
}
static void mix(uint8_t s[16], int inv) {
    for (unsigned i = 0; i < 16; i += 4) {
        uint8_t a = s[i], b = s[i + 1], c = s[i + 2], d = s[i + 3];
        if (inv) {
            s[i] = mul(a, 14) ^ mul(b, 11) ^ mul(c, 13) ^ mul(d, 9);
            s[i + 1] = mul(a, 9) ^ mul(b, 14) ^ mul(c, 11) ^ mul(d, 13);
            s[i + 2] = mul(a, 13) ^ mul(b, 9) ^ mul(c, 14) ^ mul(d, 11);
            s[i + 3] = mul(a, 11) ^ mul(b, 13) ^ mul(c, 9) ^ mul(d, 14);
        } else {
            s[i] = mul(a, 2) ^ mul(b, 3) ^ c ^ d;
            s[i + 1] = a ^ mul(b, 2) ^ mul(c, 3) ^ d;
            s[i + 2] = a ^ b ^ mul(c, 2) ^ mul(d, 3);
            s[i + 3] = mul(a, 3) ^ b ^ c ^ mul(d, 2);
        }
    }
}
void aes_encrypt(const aes128 *a, const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    memcpy(s, in, 16);
    add(s, a->round);
    for (unsigned r = 1; r <= 10; r++) {
        for (unsigned i = 0; i < 16; i++)
            s[i] = sbox[s[i]];
        shift(s, 0);
        if (r != 10)
            mix(s, 0);
        add(s, a->round + 16 * r);
    }
    memcpy(out, s, 16);
}
void aes_decrypt(const aes128 *a, const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    memcpy(s, in, 16);
    add(s, a->round + 160);
    for (int r = 9; r >= 0; r--) {
        shift(s, 1);
        for (unsigned i = 0; i < 16; i++)
            s[i] = ibox[s[i]];
        add(s, a->round + 16 * r);
        if (r)
            mix(s, 1);
    }
    memcpy(out, s, 16);
}
void ctr_init(aes_ctr *c, const uint8_t key[16], const uint8_t iv[16], unsigned bytes) {
    aes_init(&c->aes, key);
    memcpy(c->iv, iv, 16);
    c->used = 16;
    c->counter_bytes = bytes;
}
void ctr_xor(aes_ctr *c, uint8_t *p, size_t n) {
    while (n--) {
        if (c->used == 16) {
            aes_encrypt(&c->aes, c->iv, c->block);
            for (int i = 15; i >= 16 - (int)c->counter_bytes; i--)
                if (++c->iv[i])
                    break;
            c->used = 0;
        }
        *p++ ^= c->block[c->used++];
    }
}

/* Little-endian 32-bit limbs, Montgomery multiplication. At most 1024 bits. */
#define LIMBS 32
typedef uint32_t bn[LIMBS];
typedef struct {
    bn n, rr;
    unsigned words;
    uint32_t inv;
} mont;
static int cmp(const uint32_t *a, const uint32_t *b, unsigned n) {
    while (n--) {
        if (a[n] > b[n])
            return 1;
        if (a[n] < b[n])
            return -1;
    }
    return 0;
}
static void sub(uint32_t *a, const uint32_t *b, unsigned n) {
    uint64_t borrow = 0;
    for (unsigned i = 0; i < n; i++) {
        uint64_t x = (uint64_t)b[i] + borrow;
        borrow = (uint64_t)a[i] < x;
        a[i] = (uint32_t)((uint64_t)a[i] - x);
    }
}
static void twice(uint32_t *a, const uint32_t *n, unsigned w) {
    uint32_t carry = 0;
    for (unsigned i = 0; i < w; i++) {
        uint32_t t = a[i] >> 31;
        a[i] = (a[i] << 1) | carry;
        carry = t;
    }
    if (carry || cmp(a, n, w) >= 0)
        sub(a, n, w);
}
static void mont_init(mont *m, const uint32_t *n, unsigned w) {
    memset(m, 0, sizeof(*m));
    m->words = w;
    memcpy(m->n, n, w * 4);
    uint32_t x = 1;
    for (unsigned i = 0; i < 5; i++)
        x *= 2 - n[0] * x;
    m->inv = 0 - x;
    m->rr[0] = 1;
    for (unsigned i = 0; i < 64 * w; i++)
        twice(m->rr, n, w);
}
static void mm(const mont *m, const uint32_t *a, const uint32_t *b, uint32_t *out) {
    uint32_t t[2 * LIMBS + 2] = {0};
    unsigned w = m->words;
    for (unsigned i = 0; i < w; i++) {
        uint64_t c = 0;
        for (unsigned j = 0; j < w; j++) {
            uint64_t v = (uint64_t)a[i] * b[j] + t[i + j] + c;
            t[i + j] = (uint32_t)v;
            c = v >> 32;
        }
        unsigned k = i + w;
        while (c) {
            uint64_t v = (uint64_t)t[k] + c;
            t[k++] = (uint32_t)v;
            c = v >> 32;
        }
    }
    for (unsigned i = 0; i < w; i++) {
        uint32_t q = t[i] * m->inv;
        uint64_t c = 0;
        for (unsigned j = 0; j < w; j++) {
            uint64_t v = (uint64_t)q * m->n[j] + t[i + j] + c;
            t[i + j] = (uint32_t)v;
            c = v >> 32;
        }
        unsigned k = i + w;
        while (c) {
            uint64_t v = (uint64_t)t[k] + c;
            t[k++] = (uint32_t)v;
            c = v >> 32;
        }
    }
    memcpy(out, t + w, w * 4);
    if (t[2 * w] || cmp(out, m->n, w) >= 0)
        sub(out, m->n, w);
    secure_clear(t, sizeof(t));
}
static void power(const mont *m, const uint32_t *a, const uint32_t *e, uint32_t *out) {
    bn x = {0}, r = {1}, one = {1};
    mm(m, a, m->rr, x);
    mm(m, r, m->rr, r);
    for (int bit = (int)m->words * 32 - 1; bit >= 0; bit--) {
        mm(m, r, r, r);
        if ((e[bit / 32] >> (bit % 32)) & 1)
            mm(m, r, x, r);
    }
    mm(m, r, one, out);
    secure_clear(x, sizeof(x));
    secure_clear(r, sizeof(r));
}
static void from_bytes(uint32_t *a, const uint8_t *p, unsigned w) {
    for (unsigned i = 0; i < w; i++) {
        unsigned k = (w - 1 - i) * 4;
        a[i] = (uint32_t)p[k] << 24 | (uint32_t)p[k + 1] << 16 | (uint32_t)p[k + 2] << 8 | p[k + 3];
    }
}
static void to_bytes(uint8_t *p, const uint32_t *a, unsigned w) {
    for (unsigned i = 0; i < w; i++)
        for (unsigned j = 0; j < 4; j++)
            p[(w - 1 - i) * 4 + j] = (uint8_t)(a[i] >> (24 - 8 * j));
}
static uint32_t modsmall(const uint32_t *a, unsigned w, uint32_t p) {
    uint64_t r = 0;
    while (w--)
        r = ((r << 32) | a[w]) % p;
    return (uint32_t)r;
}
static void dec(uint32_t *a, unsigned w) {
    for (unsigned i = 0; i < w; i++)
        if (a[i]--)
            break;
}
static int prime(uint32_t *p) {
    for (unsigned k = 3; k < 2000; k += 2)
        if (modsmall(p, 16, k) == 0)
            return 0;
    if (modsmall(p, 16, 65537) == 1)
        return 0;
    mont m;
    mont_init(&m, p, 16);
    bn d = {0}, pm1 = {0}, x = {0}, a = {0}, one = {1};
    memcpy(pm1, p, 64);
    dec(pm1, 16);
    memcpy(d, pm1, 64);
    unsigned s = 0;
    while (!(d[0] & 1)) {
        for (unsigned i = 0; i < 16; i++)
            d[i] = (d[i] >> 1) | (i < 15 ? d[i + 1] << 31 : 0);
        s++;
    }
    for (unsigned round = 0; round < 64; round++) {
        /* Uniform rejection sampling for a in [2,p-2]. */
        do {
            if (random_bytes(a, 64))
                return -1;
        } while (cmp(a, one, 16) <= 0 || cmp(a, pm1, 16) >= 0);
        power(&m, a, d, x);
        if (cmp(x, one, 16) == 0 || cmp(x, pm1, 16) == 0)
            continue;
        unsigned j;
        for (j = 1; j < s; j++) {
            bn tmp = {0};
            mm(&m, x, m.rr, tmp);
            mm(&m, tmp, tmp, tmp);
            mm(&m, tmp, one, x);
            if (cmp(x, pm1, 16) == 0)
                break;
        }
        if (j == s)
            return 0;
    }
    return 1;
}
static int genprime(uint32_t *p) {
    for (unsigned attempt = 0; attempt < 100000; attempt++) {
        if (random_bytes(p, 64))
            return -1;
        p[0] |= 1;
        p[15] |= 0xc0000000;
        int r = prime(p);
        if (r)
            return r < 0 ? -1 : 0;
    }
    return -1;
}
static void product(const uint32_t *a, const uint32_t *b, uint32_t *out) {
    memset(out, 0, 128);
    for (unsigned i = 0; i < 16; i++) {
        uint64_t c = 0;
        for (unsigned j = 0; j < 16; j++) {
            uint64_t v = (uint64_t)a[i] * b[j] + out[i + j] + c;
            out[i + j] = (uint32_t)v;
            c = v >> 32;
        }
        out[i + 16] = (uint32_t)c;
    }
}
int rsa_generate(uint8_t modulus[128], uint8_t exponent[128]) {
    bn p = {0}, q = {0}, n = {0}, phi = {0};
    uint32_t wide[33] = {0};
    int rc = -1;
    if (genprime(p) || genprime(q))
        goto done;
    while (cmp(p, q, 16) == 0)
        if (genprime(q))
            goto done;
    product(p, q, n);
    to_bytes(modulus, n, 32);
    dec(p, 16);
    dec(q, 16);
    product(p, q, phi);
    uint32_t rem = modsmall(phi, 32, 65537),
             inv = 1; /* Small inverse: bounded and outside stream path. */
    while ((uint64_t)rem * inv % 65537 != 1)
        if (++inv == 65537)
            goto done;
    uint32_t k = 65537 - inv;
    uint64_t c = 1;
    for (unsigned i = 0; i < 32; i++) {
        uint64_t v = (uint64_t)phi[i] * k + c;
        wide[i] = (uint32_t)v;
        c = v >> 32;
    }
    wide[32] = (uint32_t)c;
    uint64_t r = 0;
    for (int i = 32; i >= 0; i--) {
        uint64_t v = (r << 32) | wide[i];
        wide[i] = (uint32_t)(v / 65537);
        r = v % 65537;
    }
    if (r || wide[32])
        goto done;
    to_bytes(exponent, wide, 32);
    rc = 0;
done:
    secure_clear(p, sizeof(p));
    secure_clear(q, sizeof(q));
    secure_clear(phi, sizeof(phi));
    secure_clear(wide, sizeof(wide));
    return rc;
}
int rsa_apply(const uint8_t input[128], const uint8_t exponent[128], const uint8_t modulus[128],
              uint8_t output[128]) {
    bn a = {0}, e = {0}, n = {0}, r = {0};
    mont m;
    from_bytes(a, input, 32);
    from_bytes(e, exponent, 32);
    from_bytes(n, modulus, 32);
    if (!(n[0] & 1) || !(n[31] & 0x80000000) || cmp(a, n, 32) >= 0)
        return -1;
    mont_init(&m, n, 32);
    power(&m, a, e, r);
    to_bytes(output, r, 32);
    secure_clear(e, sizeof(e));
    secure_clear(r, sizeof(r));
    return 0;
}
